// Writes server/src/packs.generated.ts: the server entry point of each private pack (privado/<pack>/server.ts).
// Without privado/ (the public build) the list is empty. The file is not committed (.gitignore): it would name the
// private packs. Runs before type checks, builds and server tests (package.json).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const privado = path.join(root, 'privado');
const out = path.join(root, 'server', 'src', 'packs.generated.ts');

const packs = fs.existsSync(privado)
  ? fs
      .readdirSync(privado)
      .filter((name) => /^[a-z0-9][a-z0-9-]*$/.test(name))
      .filter((name) => fs.existsSync(path.join(privado, name, 'server.ts')))
      .sort()
  : [];

const lines = [
  '// Generated by scripts/generate-packs.mjs (not committed): the private packs found in privado/.',
  // Parent folders first, as the lint's import order wants
  ...packs.map((name, i) => `import pack${i} from '../../privado/${name}/server.js';`),
  "import type { PackServerEntry } from './packTypes.js';",
  '',
  'export const PACK_SERVERS: ReadonlyArray<{ name: string; create: PackServerEntry }> = [',
  ...packs.map((name, i) => `  { name: '${name}', create: pack${i} },`),
  '];',
  '',
];
const text = lines.join('\n');
if (!fs.existsSync(out) || fs.readFileSync(out, 'utf8') !== text) fs.writeFileSync(out, text);
console.log(`[packs] ${packs.length ? packs.join(', ') : 'sin paquetes privados'}`);
